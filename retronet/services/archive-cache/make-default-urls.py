#!/usr/bin/env python3
"""Writes default-urls.txt, the sites VintageHive itself features, from a VintageHive checkout:

    make-default-urls.py <VintageHive checkout> > default-urls.txt

- the portal's link list (kDefaultLinks in Data/Contexts/HiveDbContext.cs), and
- the domains its HTTP proxy passes through to the live web (HelperProcessor.cs). Those are
  retro-friendly sites of today; some existed in 1999 and are worth a look in the archive.
URLs only, sorted, one per line.
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
hive = (src / "Data/Contexts/HiveDbContext.cs").read_text(encoding="utf-8-sig")
helper = (src / "Processors/HelperProcessor.cs").read_text(encoding="utf-8-sig")

block = hive[hive.index("kDefaultLinks"):]
block = block[:block.index("};")]
links = re.findall(r'\{\s*"[^"]*",\s*"(https?://[^"]+)"\s*\}', block)

domains = re.findall(r'const string EXT_[A-Z0-9_]+ = "([^"]+)";', helper)

urls = set()
for u in links:
    urls.add(u if re.match(r"^https?://[^/]+/", u) else u + "/")
for d in domains:
    urls.add(f"http://{d}/" if d.count(".") > 1 else f"http://www.{d}/")

print("# Sites VintageHive features (portal links and its live-site list), for retronet-warm.")
print("# Generated by make-default-urls.py from VintageHive " + (sys.argv[2] if len(sys.argv) > 2 else "") .strip())
for u in sorted(urls):
    print(u)
